#!/usr/bin/env python3
"""Convert mysql_recovery_pro CSV output to canonical typed dataset format.

This adapter bridges `recovered.csv` generated by `mysql_recovery_pro` and the
canonical ground truth / comparator format required by `comparator.py` and
`_load_typed_result` in `experiment.py`.
"""

from __future__ import annotations

import base64
import csv
from datetime import date, datetime, timedelta
from decimal import Decimal
import json
from pathlib import Path
import re
from typing import Any, Dict, Iterable, List, Optional, Tuple

from scripts.disaster_harness.ground_truth import (
    GROUND_TRUTH_VERSION,
    TYPED_ENCODING_VERSION,
    canonical_schema,
    canonical_value,
    row_hash,
    schema_fingerprint,
)
from scripts.disaster_harness.manifest import canonical_json, sha256_bytes


def _unescape_csv_text(text: str) -> str:
    """Decode the backslash escapes emitted by csv_escape_text_preserving_controls.

    The recovery CSV renderer writes \\t \\n \\r \\\\ and \\u00XX for bytes that
    would otherwise break single-line CSV records. Mirror that exact alphabet
    here so the canonical dataset sees the original bytes again.
    """
    if "\\" not in text:
        return text
    out: List[str] = []
    i = 0
    n = len(text)
    while i < n:
        char = text[i]
        if char != "\\" or i + 1 >= n:
            out.append(char)
            i += 1
            continue
        nxt = text[i + 1]
        if nxt == "t":
            out.append("\t")
            i += 2
        elif nxt == "n":
            out.append("\n")
            i += 2
        elif nxt == "r":
            out.append("\r")
            i += 2
        elif nxt == "\\":
            out.append("\\")
            i += 2
        elif nxt == "u" and i + 5 < n + 1 and i + 5 <= n and re.fullmatch(
                r"[0-9a-fA-F]{4}", text[i + 2:i + 6]):
            out.append(chr(int(text[i + 2:i + 6], 16)))
            i += 6
        else:
            # Unknown escape: keep both characters verbatim so nothing is lost.
            out.append(char)
            i += 1
    return "".join(out)


def _parse_csv_cell(raw_text: str, column_def: Dict[str, Any]) -> Any:
    """Parse a CSV cell string back to a Python object matching column_def type.

    In MySQL recovery CSV exports:
    - NULL is typically represented as 'NULL' or empty string depending on column nullability.
    - Hex encoded binaries often appear as '0x...' or raw bytes.
    - JSON strings appear as JSON strings.
    - Decimal numbers appear as numeric strings.
    - Integers appear as numeric strings.
    """
    if isinstance(raw_text, (bytes, bytearray, memoryview)):
        # The SQL exporter emits binary columns as UNHEX(...); the SQL parser
        # decodes those to raw bytes, which is already the canonical form.
        return bytes(raw_text)
    if raw_text is None:
        return None
    raw_type = str(column_def.get("type", column_def.get("data_type", ""))).lower()
    base_type = raw_type.split("(", 1)[0].strip()
    if " " in base_type:
        base_type = base_type.split()[0]
    unsigned = "unsigned" in raw_type

    # For nullable columns, raw_text == "NULL" is always None.
    # Empty string "" is None for all nullable columns except SET (where empty string represents empty set).
    if column_def.get("nullable", True):
        if raw_text == "NULL":
            return None
        if raw_text == "":
            if base_type == "set":
                return set()
            return None

    # BIT fields are exported as decimal unsigned integers by the recovery
    # decoder.  Treat them as numeric rather than TEXT so canonical truth (which
    # represents a BIT value as an integer) can compare byte-for-byte.
    if base_type == "bit":
        if raw_text == "" or raw_text == "NULL":
            return None
        return int(raw_text, 0)

    # YEAR is a numeric one-byte on-page field and is emitted as a decimal year.
    if base_type == "year":
        if raw_text == "" or raw_text == "NULL":
            return None
        return int(raw_text)

    # Nullable empty strings vs NULL:
    # If the column is numeric or date/time and cell is empty or 'NULL', treat as None if nullable
    if raw_text == "" and column_def.get("nullable", True) and base_type not in ("varchar", "char", "text", "blob", "binary", "varbinary", "set", "json"):
        return None

    if base_type in ("int", "tinyint", "smallint", "mediumint", "bigint", "integer"):
        if raw_text == "" or raw_text == "NULL":
            return None
        return int(raw_text)

    if base_type in ("decimal", "numeric"):
        if raw_text == "" or raw_text == "NULL":
            return None
        return Decimal(raw_text)

    if base_type in ("float", "double", "real"):
        if raw_text == "" or raw_text == "NULL":
            return None
        return float(raw_text)

    if base_type == "json":
        if raw_text == "" or raw_text == "NULL":
            return None
        unescaped = _unescape_csv_text(raw_text) if "\\" in raw_text else raw_text
        return unescaped.strip()

    if base_type == "set":
        if raw_text == "" and column_def.get("nullable", True):
            # Could be NULL or empty set. If empty text was decoded, it represents empty set.
            return set()
        if raw_text == "NULL":
            return None
        return set(raw_text.split(",")) if raw_text else set()

    if base_type == "date":
        if raw_text == "" or raw_text == "NULL":
            return None
        try:
            return date.fromisoformat(raw_text.strip())
        except Exception:
            return raw_text

    if base_type in ("datetime", "timestamp"):
        if raw_text == "" or raw_text == "NULL":
            return None
        try:
            return datetime.fromisoformat(raw_text.strip())
        except Exception:
            return raw_text

    if base_type == "time":
        if raw_text == "" or raw_text == "NULL":
            return None
        try:
            s_t = raw_text.strip()
            sign = -1 if s_t.startswith("-") else 1
            raw = s_t.lstrip("-")
            parts = raw.split(":")
            h, m = int(parts[0]), int(parts[1])
            sec_parts = parts[2].split(".")
            s = int(sec_parts[0])
            us = int(sec_parts[1].ljust(6, "0")[:6]) if len(sec_parts) > 1 else 0
            if sign == -1 and (h != 0 or m != 0 or s != 0 or us != 0):
                return -(timedelta(hours=h, minutes=m, seconds=s, microseconds=us))
            return timedelta(hours=h, minutes=m, seconds=s, microseconds=us)
        except Exception:
            return raw_text

    if base_type in ("binary", "varbinary", "blob", "tinyblob", "mediumblob", "longblob"):
        if raw_text.startswith("0x") or raw_text.startswith("0X"):
            try:
                return bytes.fromhex(raw_text[2:])
            except ValueError:
                pass
        if raw_text.startswith("UNHEX('") and raw_text.endswith("')"):
            try:
                return bytes.fromhex(raw_text[7:-2])
            except ValueError:
                pass
        if len(raw_text) % 2 == 0 and re.fullmatch(r"[0-9A-Fa-f]+", raw_text):
            return bytes.fromhex(raw_text)
        return raw_text.encode("utf-8")

    # Strings, dates, times, enums, sets: undo the control-byte escapes the CSV
    # renderer applies so the canonical value holds the original bytes.
    if isinstance(raw_text, str):
        val = _unescape_csv_text(raw_text) if "\\" in raw_text else raw_text
        col_charset = str(column_def.get("charset") or "").lower()
        if "latin1" in col_charset:
            try:
                raw_b = val.encode("utf-8", errors="surrogateescape")
                val = raw_b.decode("latin1")
            except Exception:
                pass
        else:
            # For non-latin1 text (utf8/utf8mb4), if any surrogate escapes leaked from
            # off-page binary pointer fragments, sanitize them to replacement character
            # so canonical JSON serialization never crashes.
            try:
                val.encode("utf-8")
            except UnicodeEncodeError:
                raw_b = val.encode("utf-8", errors="surrogateescape")
                val = raw_b.decode("utf-8", errors="replace")
        return val
    return raw_text


def csv_to_canonical_dataset(
    csv_path: Path,
    database: str,
    table: str,
    schema: Dict[str, Any],
    mysql_version: str = "",
    metadata: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Read recovered.csv and build a canonical typed dataset matching ground_truth.py."""
    canonical_sch = canonical_schema(schema["columns"], schema["primary_key"])
    fingerprint = schema_fingerprint(canonical_sch)
    by_name = {col["name"]: col for col in canonical_sch["columns"]}

    canonical_rows = []
    duplicate_keys = []
    seen = set()

    if not csv_path.is_file():
        raise FileNotFoundError(f"recovered CSV file does not exist: {csv_path}")

    with open(csv_path, mode="r", encoding="utf-8", errors="surrogateescape", newline="") as f:
        # Detect delimiter / header
        reader = csv.reader(f)
        header = next(reader, None)
        if header is None:
            header = []

        # Check if header matches column names or if it is data
        has_header = False
        if header:
            norm_header = [h.strip().strip("`").strip('"') for h in header]
            expected_names = [col["name"] for col in canonical_sch["columns"]]
            if any(name in norm_header for name in expected_names):
                has_header = True
                col_mapping = norm_header
            else:
                # First row was data!
                col_mapping = expected_names[:len(header)]
                row_data = dict(zip(col_mapping, header))
                parsed_values = {
                    col_name: _parse_csv_cell(row_data.get(col_name), by_name[col_name])
                    for col_name in [col["name"] for col in canonical_sch["columns"]]
                    if col_name in by_name
                }
                # Form PK
                pk_vals = [canonical_value(parsed_values[k], by_name[k].get("type", "")) for k in canonical_sch["primary_key"]]
                pk_key = canonical_json(pk_vals)
                if pk_key in seen:
                    duplicate_keys.append(pk_key)
                seen.add(pk_key)
                canonical_rows.append({
                    "pk": pk_vals,
                    "values": {
                        name: canonical_value(parsed_values.get(name), by_name[name].get("type", ""))
                        for name in [c["name"] for c in canonical_sch["columns"]]
                    },
                    "row_hash": row_hash(canonical_sch, parsed_values),
                })

        for row in reader:
            if not row or (len(row) == 1 and not row[0].strip()):
                continue
            row_dict = dict(zip(col_mapping, row))
            parsed_values = {}
            for col in canonical_sch["columns"]:
                name = col["name"]
                cell = row_dict.get(name)
                parsed_values[name] = _parse_csv_cell(cell, col)

            pk_vals = [canonical_value(parsed_values[k], by_name[k].get("type", "")) for k in canonical_sch["primary_key"]]
            pk_key = canonical_json(pk_vals)
            if pk_key in seen:
                duplicate_keys.append(pk_key)
            seen.add(pk_key)
            canonical_rows.append({
                "pk": pk_vals,
                "values": {
                    name: canonical_value(parsed_values.get(name), by_name[name].get("type", ""))
                    for name in [c["name"] for c in canonical_sch["columns"]]
                },
                "row_hash": row_hash(canonical_sch, parsed_values),
            })

    canonical_rows.sort(key=lambda r: canonical_json(r["pk"]))
    valid = bool(canonical_sch["primary_key"]) and not duplicate_keys
    document = {
        "ground_truth_version": GROUND_TRUTH_VERSION,
        "typed_encoding_version": TYPED_ENCODING_VERSION,
        "database": database,
        "table": table,
        "mysql_version": mysql_version,
        "schema": canonical_sch,
        "schema_fingerprint": fingerprint,
        "rows": canonical_rows,
        "row_count": len(canonical_rows),
        "duplicate_primary_keys": sorted(set(duplicate_keys)),
        "status": "SEALED_READY" if valid else "NOT_COMPARABLE",
        "metadata": metadata or {},
    }
    document["dataset_sha256"] = sha256_bytes(canonical_json({
        "schema_fingerprint": fingerprint,
        "rows": canonical_rows,
    }).encode("utf-8"))
    return document
