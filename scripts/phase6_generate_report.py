#!/usr/bin/env python3
"""
Phase 6: Final Validation Report Generator

Aggregates results from:
  - P0 regression tests (unit tests with ASan/UBSan)
  - P1 format correctness fuzz tests
  - Phase 5 disaster recovery matrix
  - Build verification

Produces a comprehensive HTML/JSON report.
"""

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path


REPORT_TEMPLATE_HTML = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>MySQL Recovery Pro — Final Validation Report</title>
<style>
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; max-width: 960px; margin: 40px auto; padding: 0 20px; color: #333; }}
  h1, h2, h3 {{ color: #1a1a2e; }}
  .summary {{ background: #f8f9fa; border-radius: 8px; padding: 20px; margin: 20px 0; }}
  .pass {{ color: #28a745; font-weight: bold; }}
  .fail {{ color: #dc3545; font-weight: bold; }}
  table {{ border-collapse: collapse; width: 100%; margin: 16px 0; }}
  th, td {{ border: 1px solid #dee2e6; padding: 8px 12px; text-align: left; }}
  th {{ background: #e9ecef; }}
  tr.pass-row {{ background: #f0fff4; }}
  tr.fail-row {{ background: #fff5f5; }}
  .section {{ margin: 32px 0; }}
  .timestamp {{ color: #6c757d; font-size: 0.9em; }}
</style>
</head>
<body>
<h1>MySQL Recovery Pro — Final Validation Report</h1>
<p class="timestamp">Generated: {timestamp}</p>

<div class="summary">
  <h2>Summary</h2>
  <p>Overall Status: <span class="{overall_class}">{overall_status}</span></p>
  <p>Total Tests: {total_tests} | Passed: {passed} | Failed: {failed}</p>
</div>

{content}

<hr>
<p class="timestamp">Report generated by Phase 6 CI Pipeline</p>
</body>
</html>"""


SECTION_TEMPLATE = """
<div class="section">
  <h2>{title}</h2>
  <p>Status: <span class="{status_class}">{status}</span></p>
  {details}
</div>
"""


TABLE_TEMPLATE = """
<table>
  <tr><th>Test</th><th>Result</th><th>Details</th></tr>
  {rows}
</table>"""


ROW_TEMPLATE = '<tr class="{row_class}"><td>{name}</td><td class="{result_class}">{result}</td><td>{details}</td></tr>'


def run_cmd(test_bin: str, timeout: int = 60) -> dict:
    """Run a test binary and capture results."""
    result = {"name": os.path.basename(test_bin), "passed": False, "output": "", "details": ""}
    try:
        proc = subprocess.run(
            [test_bin, "--gtest_print_time=0"],
            capture_output=True, text=True, timeout=timeout
        )
        result["output"] = proc.stdout + proc.stderr
        if proc.returncode == 0 and "PASSED" in proc.stdout:
            result["passed"] = True
            result["details"] = "All tests passed"
        else:
            result["details"] = "Some tests failed"
            # Extract failed test names
            for line in proc.stdout.split("\n"):
                if "FAILED" in line:
                    result["details"] += f"\n  {line.strip()}"
    except subprocess.TimeoutExpired:
        result["details"] = f"Timed out ({timeout}s)"
    except FileNotFoundError:
        result["details"] = "Binary not found"
    return result


def check_build(build_dir: str) -> list:
    """Verify all required binaries exist."""
    required = [
        "libdbrecovery_innodb.so",
        "mysql_recovery_pro",
        "tests/test_p0_regression",
        "tests/test_p1_salvage_fuzz",
        "tests/test_p1_layout_fuzz",
        "tests/test_p1_type_classifier_fuzz",
    ]
    results = []
    for bin in required:
        full_path = os.path.join(build_dir, bin)
        exists = os.path.exists(full_path)
        size = os.path.getsize(full_path) if exists else 0
        results.append({
            "name": bin,
            "passed": exists,
            "details": f"{size:,} bytes" if exists else "Missing",
        })
    return results


def generate_report(build_dir: str, test_results: list, matrix_results: str = None, output: str = "validation_report.html") -> str:
    """Generate the final HTML report."""
    rows_html = ""
    passed = 0
    failed = 0

    for suite in test_results:
        for test in suite.get("tests", [suite]):
            row_class = "pass-row" if test["passed"] else "fail-row"
            result_class = "pass" if test["passed"] else "fail"
            result_text = "PASS" if test["passed"] else "FAIL"
            rows_html += ROW_TEMPLATE.format(
                row_class=row_class,
                name=test["name"],
                result_class=result_class,
                result=result_text,
                details=test["details"],
            )
            if test["passed"]:
                passed += 1
            else:
                failed += 1

    content = ""

    # Build verification
    build_results = check_build(build_dir)
    build_rows = ""
    for b in build_results:
        rc = "pass-row" if b["passed"] else "fail-row"
        rsc = "pass" if b["passed"] else "fail"
        build_rows += ROW_TEMPLATE.format(row_class=rc, name=b["name"], result_class=rsc, result=b["passed"], details=b["details"])
    content += SECTION_TEMPLATE.format(
        title="Build Verification",
        status_class="pass" if all(b["passed"] for b in build_results) else "fail",
        status="PASS" if all(b["passed"] for b in build_results) else "FAIL",
        details=TABLE_TEMPLATE.format(rows=build_rows),
    )

    # Test results
    content += SECTION_TEMPLATE.format(
        title="Test Suite Results",
        status_class="pass" if failed == 0 else "fail",
        status="PASS" if failed == 0 else "FAIL",
        details=TABLE_TEMPLATE.format(rows=rows_html),
    )

    # Matrix results
    if matrix_results and os.path.exists(matrix_results):
        try:
            with open(matrix_results) as f:
                matrix = json.load(f)
            matrix_rows = ""
            for entry in matrix:
                ver = entry.get("mysql_version", "?")
                sce = entry.get("scenario", "?")
                fs = entry.get("filesystem", "?")
                rows = entry.get("recovered_rows", 0)
                ms = entry.get("elapsed_ms", 0)
                name = f"{ver} / {sce} / {fs}"
                matrix_rows += ROW_TEMPLATE.format(
                    row_class="pass-row",
                    name=name,
                    result_class="pass",
                    result=rows,
                    details=f"{ms} ms",
                )
            content += SECTION_TEMPLATE.format(
                title="Disaster Recovery Matrix",
                status_class="pass",
                status=f"{len(matrix)} tests",
                details=TABLE_TEMPLATE.format(rows=matrix_rows),
            )
        except (json.JSONDecodeError, IOError) as e:
            content += SECTION_TEMPLATE.format(
                title="Disaster Recovery Matrix",
                status_class="fail",
                status="ERROR",
                details=f"<p>Could not load matrix results: {e}</p>",
            )

    total_tests = passed + failed
    overall_status = "PASS" if failed == 0 else "FAIL"
    overall_class = "pass" if failed == 0 else "fail"

    html = REPORT_TEMPLATE.format(
        timestamp=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        overall_status=overall_status,
        overall_class=overall_class,
        total_tests=total_tests,
        passed=passed,
        failed=failed,
        content=content,
    )

    with open(output, "w") as f:
        f.write(html)
    print(f"Report written to {output}")

    # Also write JSON version
    json_output = output.replace(".html", ".json")
    report_data = {
        "timestamp": datetime.now().isoformat(),
        "overall_status": overall_status,
        "total_tests": total_tests,
        "passed": passed,
        "failed": failed,
        "build": build_results,
        "tests": test_results,
    }
    with open(json_output, "w") as f:
        json.dump(report_data, f, indent=2)
    print(f"JSON report written to {json_output}")

    return overall_status


def main():
    parser = argparse.ArgumentParser(description="Generate final validation report")
    parser.add_argument("--build-dir", default="build", help="Build directory")
    parser.add_argument("--matrix-results", default=None, help="Phase 5 summary.json")
    parser.add_argument("--output", default="validation_report.html", help="Output HTML file")
    args = parser.parse_args()

    build_dir = os.path.abspath(args.build_dir)
    if not os.path.exists(build_dir):
        print(f"ERROR: Build directory not found: {build_dir}")
        sys.exit(1)

    # Run all tests
    test_results = []
    test_bins = [
        os.path.join(build_dir, "tests", "test_p0_regression"),
        os.path.join(build_dir, "tests", "test_p1_salvage_fuzz"),
        os.path.join(build_dir, "tests", "test_p1_layout_fuzz"),
        os.path.join(build_dir, "tests", "test_p1_type_classifier_fuzz"),
    ]

    for tb in test_bins:
        result = run_cmd(tb)
        test_results.append({"suite": os.path.basename(tb), "tests": [result]})

    status = generate_report(build_dir, test_results, args.matrix_results, args.output)
    sys.exit(0 if status == "PASS" else 1)


if __name__ == "__main__":
    main()